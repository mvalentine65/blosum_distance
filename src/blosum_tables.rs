/// Marks a byte blosum62_distance would have rejected.
pub const INVALID: u8 = 255;

/// Byte -> matrix index, mirroring bio's lookup(). '-' folds to '*' as the
/// callers do before scoring.
const fn build_xlat() -> [u8; 256] {
    let mut t = [INVALID; 256];
    let mut c = 65usize;
    while c < 88 {
        t[c] = (c - 65) as u8; // A..W
        c += 1;
    }
    t[b'X' as usize] = 25;
    t[b'Y' as usize] = 23;
    t[b'Z' as usize] = 24;
    t[b'*' as usize] = 26;
    t[b'-' as usize] = 26;
    t
}
pub const XLAT: [u8; 256] = build_xlat();

/// blosum62(c, c) is the matrix diagonal -- a per-character constant, so the
/// two self-score sums need no cross lookup.
const fn build_diag() -> [i32; 27] {
    let mut d = [0i32; 27];
    let mut i = 0usize;
    while i < 27 {
        d[i] = BLOSUM[27 * i + i];
        i += 1;
    }
    d
}
pub const DIAG: [i32; 27] = build_diag();
